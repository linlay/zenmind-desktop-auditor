import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createPublicKey } from 'node:crypto';
import JSZip from 'jszip';
import { keys, token, desktopConfig } from './helpers.mjs';
import { parseConfig } from '../backend/config.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
test('published Desktop trust profiles require an explicit environment and never overwrite configuration', async t => {
  const value = JSON.parse(await readFile(path.join(root, 'config/transit-hub-dev.desktop.example.json'), 'utf8'));
  parseConfig(value); assert.equal(createPublicKey(value.desktop.publicKeyPem).asymmetricKeyType, 'rsa');
  const directory = await mkdtemp(path.join(os.tmpdir(), 'auth-lab-configure-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const command = [path.join(root, 'scripts/configure.mjs'), '--data-dir', directory];
  assert.throws(() => execFileSync(process.execPath, command, { stdio: 'pipe' }));
  execFileSync(process.execPath, [...command, '--profile', 'transit-hub-dev'], { stdio: 'pipe' });
  const first = await readFile(path.join(directory, 'auth-config.json'), 'utf8');
  assert.equal(JSON.parse(first).desktop.issuer, value.desktop.issuer);
  assert.throws(() => execFileSync(process.execPath, [...command, '--profile', 'cutej-enterprise'], { stdio: 'pipe' }));
  assert.equal(await readFile(path.join(directory, 'auth-config.json'), 'utf8'), first);
  const enterpriseDirectory = path.join(directory, 'enterprise');
  execFileSync(process.execPath, [path.join(root, 'scripts/configure.mjs'), '--data-dir', enterpriseDirectory, '--profile', 'cutej-enterprise'], { stdio: 'pipe' });
  const enterprise = JSON.parse(await readFile(path.join(enterpriseDirectory, 'auth-config.json'), 'utf8'));
  parseConfig(enterprise);
  assert.equal(enterprise.desktop.issuer, 'https://eiam.gtjaqh.net/auth/oidc/5CA69847F97E4DFFBAA67966CC4ED49F');
  assert.ok(enterprise.desktop.jwksUri.endsWith('/jwk'));
  assert.notEqual(enterprise.desktop.issuer, value.desktop.issuer);
});
test('importable ZIP excludes credentials/dependencies and runs its bundled auth backend without node_modules', async t => {
  const bytes = await readFile(path.join(root, 'build/auth-lab.zip'));
  const zip = await JSZip.loadAsync(bytes, { checkCRC32: true });
  const names = Object.keys(zip.files).filter(name => !zip.files[name].dir), id = 'webapp-8c439d21b7a6ef05';
  assert.ok(names.every(name => name.startsWith(id + '/')));
  assert.ok(names.every(name => !/(?:^|\/)(?:node_modules|config|test|auth-config\.json|notes\.json|\.env|[^/]*private[^/]*)(?:\/|$)/i.test(name)));
  const manifest = JSON.parse(await zip.file(id + '/webapp.json').async('string')); assert.equal(manifest.target, 'any'); assert.equal(manifest.backend.command.type, 'electron-node');
  assert.ok(zip.file(id + '/docs/jose-LICENSE.md'));
  const directory = await mkdtemp(path.join(os.tmpdir(), 'auth-lab-package-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  for (const name of names) { const target = path.join(directory, name); const { mkdir, writeFile } = await import('node:fs/promises'); await mkdir(path.dirname(target), { recursive: true }); await writeFile(target, await zip.file(name).async('nodebuffer')); }
  const key = await keys();
  const { createServer } = await import(pathToFileURL(path.join(directory, id, 'backend/server.mjs')));
  const defaults = await createServer({ directory: path.join(directory, 'defaults-data') });
  await new Promise(resolve => defaults.listen(0, '127.0.0.1', resolve)); t.after(() => defaults.shutdown());
  const localOrigin = 'http://127.0.0.1:' + defaults.address().port;
  const defaultStatus = await fetch(localOrigin + '/api/auth/status').then(r => r.json()); assert.equal(defaultStatus.issue, ''); assert.equal(defaultStatus.oidc, true); assert.equal(defaultStatus.desktop, true); assert.equal(defaultStatus.desktopOpenUrl, 'cutej://open');
  const { loginState } = await import('../frontend/login-state.mjs');
  const desktopChoices = loginState(defaultStatus, true, localOrigin); assert.equal(desktopChoices.desktopLogin, true); assert.equal(desktopChoices.oidcLogin, true);
  const browserChoices = loginState(defaultStatus, false, localOrigin); assert.equal(browserChoices.desktopLogin, false); assert.equal(browserChoices.oidcLogin, true);
  const lanStatus = await fetch(localOrigin + '/api/auth/status', { headers: { 'x-forwarded-host': '192.168.1.8:54321' } }).then(r => r.json()); assert.equal(lanStatus.canonicalRequired, false); assert.equal(lanStatus.oidcLoginUrl, 'http://192.168.1.8:54321/api/auth/oidc/start');
  const started = await fetch(localOrigin + '/api/auth/oidc/start', { redirect: 'manual' }); assert.equal(started.status, 303);
  const target = new URL(started.headers.get('location')); assert.equal(target.origin, 'https://auth-test.zenmind.cc'); assert.equal(target.searchParams.get('callback'), localOrigin + '/api/auth/oidc/callback'); assert.equal(target.searchParams.has('client_id'), false);
  assert.equal((await fetch(localOrigin + '/api/me')).status, 401);
  const server = await createServer({ directory: path.join(directory, 'data'), rawConfig: desktopConfig(key) });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); t.after(() => server.shutdown());
  const origin = 'http://127.0.0.1:' + server.address().port;
  const response = await fetch(origin + '/api/auth/desktop-session', { method: 'POST', headers: { Origin: origin, Authorization: 'Bearer ' + await token(key.privateKey), 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(response.status, 200);
  const cookie = response.headers.get('set-cookie').split(';')[0];
  const identity = await fetch(origin + '/api/me', { headers: { Cookie: cookie } }).then(response => response.json()); assert.equal(identity.user.subject, 'alice');
});
